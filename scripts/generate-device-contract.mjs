import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'
import openapiTS, { astToString } from 'openapi-typescript'
import ts from 'typescript'
import YAML from 'yaml'
import prettier from 'prettier'

const args = process.argv.slice(2)
if (args.length !== 2 || args[0] !== '--source')
  throw new Error('Usage: node scripts/generate-device-contract.mjs --source <backend/openapi.yaml>')
const source = await readFile(resolve(args[1]))
const doc = YAML.parse(source.toString('utf8'))
const output = resolve(dirname(fileURLToPath(import.meta.url)), '../src/service/api/generated/device-metadata')
let types = astToString(await openapiTS(doc))
const parsed = ts.createSourceFile('generated.ts', types, ts.ScriptTarget.Latest, true)
const component = parsed.statements.find((n) => ts.isInterfaceDeclaration(n) && n.name.text === 'components')
const schemas = component?.members.find((n) => n.name?.getText(parsed) === 'schemas')
const name = 'NativeThingModelJsonValue'
const target = schemas?.type?.members?.find((n) => n.name?.getText(parsed) === name)
if (!target?.type || !ts.isUnionTypeNode(target.type)) throw new Error('Recursive schema structure changed')
const expression = target.type.getText(parsed)
const reference = /components\["schemas"\]\["NativeThingModelJsonValue"\]/g
if (!expression.match(reference)?.length) throw new Error('Recursive reference form changed')
const alias = expression.replace(reference, name)
types = types.slice(0, target.type.getStart(parsed)) + name + types.slice(target.type.end)
const insertion = types.indexOf('export interface components')
if (insertion < 0) throw new Error('Components interface missing')
types = types.slice(0, insertion) + `export type ${name} = ${alias};\n\n` + types.slice(insertion)
types =
  '/**\n * This file was auto-generated by openapi-typescript.\n * Do not make direct changes to the file.\n */\n\n' +
  types
types = await prettier.format(types, {
  ...JSON.parse(await readFile(resolve(output, '../../../../../.prettierrc'), 'utf8')),
  parser: 'typescript'
})
const extensionsByJsonPointer = {}
const escape = (v) => v.replaceAll('~', '~0').replaceAll('/', '~1')
function walk(value, path = '') {
  if (!value || typeof value !== 'object') return
  for (const [key, child] of Object.entries(value)) {
    const pointer = `${path}/${escape(key)}`
    if (key.startsWith('x-')) extensionsByJsonPointer[pointer] = child
    walk(child, pointer)
  }
}
walk(doc)
const operations = {}
for (const [path, item] of Object.entries(doc.paths ?? {})) {
  for (const method of ['get', 'put', 'post', 'delete', 'options', 'head', 'patch', 'trace']) {
    const op = item[method]
    if (!op) continue
    if (!op.operationId || operations[op.operationId]) throw new Error('Missing or duplicate operationId')
    operations[op.operationId] = {
      operationId: op.operationId,
      method,
      path,
      pathParameters: item.parameters ?? [],
      parameters: op.parameters ?? [],
      requestBody: op.requestBody ?? null,
      responses: op.responses ?? {},
      extensions: Object.fromEntries(Object.entries(op).filter(([k]) => k.startsWith('x-')))
    }
  }
}
const metadata = {
  componentParameters: doc.components?.parameters ?? {},
  componentRequestBodies: doc.components?.requestBodies ?? {},
  componentResponses: doc.components?.responses ?? {},
  description:
    'Mechanical constraint metadata extracted from the authoritative OpenAPI source; not a separate API contract.',
  extensionsByJsonPointer,
  openapi: doc.openapi,
  operations,
  schemas: doc.components?.schemas ?? {}
}
const sorted = (value) =>
  Array.isArray(value)
    ? value.map(sorted)
    : value && typeof value === 'object'
      ? Object.fromEntries(
          Object.keys(value)
            .sort()
            .map((k) => [k, sorted(value[k])])
        )
      : value
const json = (value) => JSON.stringify(sorted(value), null, 2) + '\n'
const sha = (value) => createHash('sha256').update(value).digest('hex')
const sidecar = json(metadata)
const manifest = {
  compatibilityTransform: {
    operation:
      'Lift the complete generated recursive schema expression to a named module alias and redirect its recursive references; no union members are changed.',
    schema: name,
    version: 'recursive-schema-alias-v1'
  },
  generator: 'openapi-typescript@7.13.0',
  openapi: doc.openapi,
  operationCount: Object.keys(operations).length,
  outputs: { 'contract-metadata.json': sha(sidecar), 'types.ts': sha(types) },
  source: 'thingspanel-backend-community/docs/initiatives/device-metadata-native-cutover/openapi.yaml',
  sourceSha256: sha(source)
}
await mkdir(output, { recursive: true })
await writeFile(resolve(output, 'types.ts'), types)
await writeFile(resolve(output, 'contract-metadata.json'), sidecar)
await writeFile(resolve(output, 'manifest.json'), json(manifest))
console.log(`Generated ${manifest.operationCount} operations; source SHA-256 ${manifest.sourceSha256}`)
